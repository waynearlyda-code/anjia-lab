// 户型数据：从户型图逐像素扫描墙体得到（图片 1440×1080，比例 14.5mm/px，
// 用图上「阳台B 3048mm」和各房间面积校准）。坐标单位 mm，x 向东，y 向南。
const PX = 14.5, OX = 320, OY = 104;
const P = (x, y) => [Math.round((x - OX) * PX), Math.round((y - OY) * PX)];

let _id = 1;
const uid = (p = 'o') => p + (_id++).toString(36) + Math.random().toString(36).slice(2, 5);

function W(a, b, t, kind, ops) {
  return { id: uid('w'), a: P(...a), b: P(...b), t: t || 120, kind: kind || 'inner', h: kind === 'rail' ? 1100 : 2800, ops: ops || [] };
}
// 门窗：from/to 用像素坐标沿墙方向给出，后面换算成离 a 端的距离
function op(type, from, to, extra) { return Object.assign({ type, from, to }, extra || {}); }

